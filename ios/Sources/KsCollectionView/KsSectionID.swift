// 配列を内部で固定件数の塊に分けて載せるための、塊の識別子 (ios/ADR-0009、ios/ADR-0010)。
// レイアウトの再解決に要する費用は 1 セクションに載る件数で決まるため、配列全体を 1 つに
// 載せず、固定件数の塊へ区切って費用の上限を配列全体の件数から切り離す。
// 塊は利用者のグループごとにその先頭から区切り、1 つの塊が 2 つのグループにまたがることはない。
// 塊の件数は列数の倍数に揃えるので、1 つの行が塊をまたぐことはない。
// 塊の分け方は利用者の宣言にも公開 API にも現れない。
internal struct KsSectionID: Hashable, @unchecked Sendable {
    // 塊が属するグループのグループの値。グループを宣言しないときは配列全体が値なし (nil) の
    // 1 つのグループになる。
    let group: AnyHashable?
    // 同じグループの値が配列の離れた位置に再び現れる不正入力を表示し続ける間、同じ値のまとまりを
    // 区別するための何回目か。正しい入力では常に 0。
    let occurrence: Int
    // グループの先頭の塊を 0 とする、グループの中での塊の並び順。
    let chunkInGroup: Int
}
