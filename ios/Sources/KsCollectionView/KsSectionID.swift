// 配列を内部で固定件数の塊に分けて載せるための、塊の順番による識別子 (ios/ADR-0009)。
// レイアウトの再解決に要する費用は 1 セクションに載る件数で決まるため、配列全体を 1 つに
// 載せず、固定件数の塊へ区切って費用の上限を配列全体の件数から切り離す。
// 塊の件数は列数の倍数に揃えるので、1 つの行が塊をまたぐことはない。
// 塊の分け方は利用者の宣言にも公開 API にも現れない。
internal struct KsSectionID: Hashable {
    // 先頭の塊を 0 とする、塊の並び順。
    let chunkIndex: Int
}
