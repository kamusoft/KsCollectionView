// 先読みの取得の単位。同じ単位を必要とするアイテムの数を数え、最後の 1 つが外れたときに取り消す。
//
// 到達点がディスクまでのときは幅を使わないので識別子だけで決まり、幅違いの宣言も 1 つの取得に
// まとまる (ローダーは同じ要求を 1 つにまとめ、取り消しに参照数を持たないため、幅違いを別に
// 数えると一方の取り消しが他方を止める)。メモリまでのときは識別子と幅 (ピクセル) で決まり、
// 幅違いは別の取得として数える。
internal struct KsPrefetchUnit: Hashable {
    let identifier: String
    let widthPixels: Int?
}
