/// 先読みする画像を表示するときのおおよその幅を表します。
///
/// 幅を指定した画像は、その幅の正方形を覆う大きさに縮小してからメモリに載せます
/// (元の画像がそれより小さければ拡大せずそのまま載せます)。高さや当てはめ方は指定しません。
/// 幅は目安で構いません。表示のときに枠の大きさと大きく違わなければ、縮小し直さずに使われます。
public enum KsWidth: Hashable, Sendable {
    /// コレクションの 1 列分の幅です。
    ///
    /// 表示領域の幅・列数・内側の余白・列の間隔から求めます。画面の向きや列数が変わった後に
    /// 始まる先読みは、新しい列の幅で行われます。
    case column

    /// ポイントで指定した固定の幅です。
    ///
    /// 0 より大きい有限の値を指定してください。それ以外の値は誤りとして扱い、デバッグビルドでは
    /// 停止し、リリースビルドでは警告を記録して幅を指定しなかったものとして扱います。
    case fixed(Double)
}
