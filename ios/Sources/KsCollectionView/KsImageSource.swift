import Foundation

/// 画像の取得元を表します。
public enum KsImageSource: Hashable, Sendable {
    /// ネットワーク上の画像を URL で指定します。
    ///
    /// `key` を指定すると、取得には URL を使い、キャッシュの項目はキーで見分けます。署名付きの
    /// URL のように取得のたびに URL が変わる画像でも、同じキーなら先読みした画像や保存済みの画像が
    /// 使われます。先読みの宣言 (``KsResource``) にも同じキーを指定してください。キーは画像の
    /// 中身を一意に特定する値にし、空文字は使わないでください。
    ///
    /// キーを指定した画像は、ローダー付属のビューに同じ URL を直接渡して表示した画像とは
    /// キャッシュを共有しません。
    case remote(URL, key: String? = nil)

    /// 端末内のファイルを URL で指定します。
    case file(URL)

    /// アプリに同梱したアセットカタログの画像を名前で指定します。
    case asset(String)
}
