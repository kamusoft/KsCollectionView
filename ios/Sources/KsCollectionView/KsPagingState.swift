/// ページングの状態です。
///
/// 状態は利用者が持ち、読み込みの進み具合に合わせて利用者が書き換えます。一覧は状態を読んで
/// 次のページを頼むかどうかと、どの表示を出すかを決めるだけで、状態を書き換えません。
public enum KsPagingState: Hashable, Sendable {
    /// 待機中です。末尾に近づくと、一覧が次のページを頼みます。項目が 1 件も無いときは、
    /// 最初のページを頼みます。
    case idle
    /// 一覧を最初から取り直しています。
    case refreshing
    /// 次のページを読み込んでいます。
    case appending
    /// 読み込みに失敗しました。一覧は次のページを自動では頼みません。
    case failed
    /// 最後のページまで読み込みました。一覧は次のページを頼みません。
    case endReached
}
