package jp.kamusoft.kscollectionview

/**
 * 項目を長押ししてドラッグで並べ替えられるようにする設定です。
 *
 * `KsCollectionView` の `reorder` 引数に渡します。[enabled] が true の間は、項目のどこでも長押しすると
 * その項目が持ち上がり、指で動かして並べ替えられます。一覧の上端・下端の近くまで運ぶと、一覧はその向きに
 * スクロールを続けます。false の間 (`reorder` を渡さない一覧も同じ) は、長押ししてもドラッグは始まりません。
 *
 * ```
 * KsCollectionView(
 *     items = viewModel.items,
 *     key = { it.id },
 *     reorder = KsReorder(
 *         enabled = viewModel.isReordering,
 *         onMove = { move ->
 *             viewModel.move(move) // 配列を並べ替えて渡し直す
 *             true                 // 受け入れた
 *         },
 *     ),
 * ) { template { item -> Row(item) } }
 * ```
 *
 * ## 置いたときの知らせ
 *
 * [onMove] は、ドラッグした項目を置いて指を離したときに 1 回だけ呼ばれます。ドラッグの途中で項目が
 * 入れ替わるたびには呼ばれません。元の位置に置いたとき、置けない場所で指を離したとき、ドラッグが
 * 取りやめになったときは呼ばれません。
 *
 * 知らせ ([KsReorderMove]) には、動かした項目と行き先 ([KsReorderDestination]) が入ります。行き先は、
 * 置いた位置の後ろに同じグループの項目があれば [KsReorderDestination.Before] でその項目を、置いた位置が
 * グループの最後 (グループを宣言していなければ一覧の最後) なら [KsReorderDestination.End] になります。
 * 項目はどちらも配列の要素そのものです。
 *
 * ## 受け入れと元に戻す
 *
 * [onMove] は、並べ替えを受け入れたかを返します。
 *
 * - true を返すと、一覧は置いた並びのまま次の配列を待ちます。受け入れたら、呼び出し側で配列を並べ替えて
 *   渡し直してください。置いた時点と同じ配列のままの描き直しでは、置いた並びのまま待ち続け、時間が経っても
 *   元には戻しません。保存に失敗したときは、並べ替える前の並びの配列を渡し直すと、その並びで表示されます
 * - false を返すと、一覧は項目を元の位置に戻します
 *
 * 一覧は呼び出し側の配列を書き換えません。ドラッグしている間に配列が渡されても、指を離すまでは表示に
 * 当てず、最新の 1 つを控えます。受け入れたら控えた配列は捨て、受け入れなかったとき・元の位置に置いたとき・
 * 取りやめになったときは、項目を元の位置に戻してから控えた最新の配列を表示します。ドラッグしている間は、
 * `paging` の次のページを頼まず、[KsScrollController] のスクロール命令も指を離して配列を表示に当てた後に
 * 実行します。
 *
 * ## グループをまたぐ移動
 *
 * `groups` でグループを宣言した一覧では、項目を別のグループへ動かせます。見出し (見出しが無ければグループと
 * グループの間) より上に置けば前のグループの末尾、下に置けば次のグループの先頭になります。知らせの
 * [KsReorderMove.group] には行き先のグループの値が入るので、受け入れる場合は項目のグループの値も
 * 書き換えてから配列を渡し直してください。項目が 1 件も無いグループは表示されないため、そこへは動かせません。
 * グループの最後の 1 件をドラッグしている間も元のグループの見出しは残り、受け入れた時点で見出しごと
 * 表示されなくなります。
 *
 * ## 長押しとタップ
 *
 * [enabled] が true の間は、長押しが並べ替えの操作になり、`onItemLongTap` の処理は動かせない項目を
 * 長押ししたときも含めて呼ばれません。`onItemTap` を渡していない項目は、タップしてもフィードバックを
 * 出しません。`onItemTap` の処理は [enabled] によらず呼ばれます。
 *
 * ## ドラッグ中の設定の変化
 *
 * ドラッグしている間に [enabled] を false にするか、`layout` の値かグループの宣言 (`groups`) を変えると、
 * ドラッグはその場で取りやめになり、項目は元の位置に戻って [onMove] は呼ばれません。
 *
 * @param Item 項目の型
 * @property enabled 並べ替えのスイッチ
 * @property onMove 置いたときの処理。メインスレッドで呼ばれます。受け入れたら true、受け入れなければ false を
 *   返します。SwiftUI などの `onMove` と同じく指を離したときに呼ばれますが、位置の番号ではなく項目で行き先を
 *   知らせ、受け入れたかを返す点が違います
 * @property canMove 項目を動かせるか。false を返した項目は長押ししても持ち上がりません。省略すると
 *   すべての項目を動かせます
 * @property canDrop 行き先に置けるか。ドラッグしている間に行き先の候補ごとに、[onMove] と同じ形の知らせを
 *   渡して呼ばれます。false を返した行き先には項目が入らず、その上で指を離すと項目は元の位置に戻ります。
 *   省略するとすべての位置に置けます。ドラッグ中に何度も呼ばれるため、軽い処理にしてください
 * @property accessibilityActions 読み上げ (TalkBack) 用の移動の操作の文言。渡すと、動かせる項目に
 *   「1 つ前へ動かす」「1 つ後ろへ動かす」の 2 つの操作が出ます。グループの先頭の項目を前へ動かすと前の
 *   グループの末尾へ、グループの最後の項目を後ろへ動かすと次のグループの先頭へ移ります。一覧の先頭の項目には
 *   前へ動かす操作が、最後の項目には後ろへ動かす操作が出ず、[canDrop] が false を返す行き先への操作も
 *   出ません。操作で動かしたときも、[onMove] の呼ばれ方と受け入れの扱いはドラッグと同じです。省略すると
 *   操作は出ません
 */
public class KsReorder<Item>(
    public val enabled: Boolean,
    public val onMove: (KsReorderMove<Item>) -> Boolean,
    public val canMove: ((Item) -> Boolean)? = null,
    public val canDrop: ((KsReorderMove<Item>) -> Boolean)? = null,
    public val accessibilityActions: KsReorderAccessibilityActions? = null,
)
